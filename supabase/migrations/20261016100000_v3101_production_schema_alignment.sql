-- Validate existing data only when the corresponding production constraint/index
-- is missing and must be created. Already-protected production tables need no scans.
do $$
begin
  if not exists (select 1 from pg_constraint where conrelid = 'public.exchange_purchases'::regclass and conname = 'exchange_purchases_foreign_amount_check')
     or not exists (select 1 from pg_constraint where conrelid = 'public.exchange_purchases'::regclass and conname = 'exchange_purchases_foreign_currency_check')
     or not exists (select 1 from pg_constraint where conrelid = 'public.exchange_purchases'::regclass and conname = 'exchange_purchases_twd_amount_check') then
    if exists (select 1 from public.exchange_purchases where foreign_amount <= 0 or twd_amount <= 0
               or foreign_currency not in ('JPY', 'KRW', 'USD', 'EUR')) then
      raise exception 'SCHEMA_ALIGNMENT_BLOCKED_EXCHANGE_DATA: rows violate production constraints';
    end if;
  end if;
  if not exists (select 1 from pg_class where relname = 'checklist_items_one_client_item_per_checklist' and relkind = 'i') and exists (
    select 1 from public.checklist_items where client_item_id is not null
    group by checklist_id, client_item_id having count(*) > 1
  ) then
    raise exception 'SCHEMA_ALIGNMENT_BLOCKED_DUPLICATE_CHECKLIST_ITEMS';
  end if;
  if not exists (select 1 from pg_class where relname = 'checklists_one_private_per_trip_owner' and relkind = 'i') and exists (
    select 1 from public.checklists where scope = 'private'
    group by trip_id, owner_user_id having count(*) > 1
  ) then
    raise exception 'SCHEMA_ALIGNMENT_BLOCKED_DUPLICATE_PRIVATE_CHECKLISTS';
  end if;
  if not exists (select 1 from pg_class where relname = 'other_info_items_one_client_item_per_trip' and relkind = 'i') and exists (
    select 1 from public.other_info_items where client_item_id is not null
    group by trip_id, client_item_id having count(*) > 1
  ) then
    raise exception 'SCHEMA_ALIGNMENT_BLOCKED_DUPLICATE_OTHER_INFO_ITEMS';
  end if;
end;
$$;


-- These Storage policies already exist from the earlier V3.5.1 migrations.
-- Preserve matching production policies; create only if a clean schema is missing one.
do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'storage' and policyname = 'expense_attachments_select_v351') then
    execute $policy$create policy expense_attachments_select_v351 on storage.objects for select to authenticated using (
      bucket_id = 'expense-attachments'
      and array_length(storage.foldername(name), 1) = 2
      and ((select public.tc_is_super_admin()) or exists (
        select 1 from public.expenses expense
        where public.tc_attachment_storage_scope(expense.trip_id) = (storage.foldername(objects.name))[1]
          and (select public.tc_is_trip_editor(expense.trip_id))
      ))
    )$policy$;
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'storage' and policyname = 'expense_attachments_insert_v351') then
    execute $policy$create policy expense_attachments_insert_v351 on storage.objects for insert to authenticated with check (
      bucket_id = 'expense-attachments'
      and array_length(storage.foldername(name), 1) = 2
      and exists (
        select 1 from public.expenses expense
        where public.tc_attachment_storage_scope(expense.trip_id) = (storage.foldername(objects.name))[1]
          and public.tc_attachment_storage_scope(expense.id::text) = (storage.foldername(objects.name))[2]
          and ((select public.tc_is_super_admin()) or (
            (select public.tc_can_write_shared_trip(expense.trip_id))
            and (expense.owner_user_id = (select auth.uid()) or expense.owner_user_id is null)
          ))
      )
    )$policy$;
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'storage' and policyname = 'expense_attachments_update_v351') then
    execute $policy$create policy expense_attachments_update_v351 on storage.objects for update to authenticated using (
      bucket_id = 'expense-attachments'
      and array_length(storage.foldername(name), 1) = 2
      and ((select public.tc_is_super_admin()) or exists (
        select 1 from public.expenses expense
        where public.tc_attachment_storage_scope(expense.trip_id) = (storage.foldername(objects.name))[1]
          and (select public.tc_can_write_shared_trip(expense.trip_id))
      ))
    ) with check (
      bucket_id = 'expense-attachments'
      and array_length(storage.foldername(name), 1) = 2
      and exists (
        select 1 from public.expenses expense
        where public.tc_attachment_storage_scope(expense.trip_id) = (storage.foldername(objects.name))[1]
          and public.tc_attachment_storage_scope(expense.id::text) = (storage.foldername(objects.name))[2]
          and ((select public.tc_is_super_admin()) or (
            (select public.tc_can_write_shared_trip(expense.trip_id))
            and (expense.owner_user_id = (select auth.uid()) or expense.owner_user_id is null)
          ))
      )
    )$policy$;
  end if;
end;
$$;


-- Align clean/local migration-built schemas with the existing production baseline.
-- This migration is intentionally forward-only and idempotent for production,
-- where the legacy schema objects already exist.
-- It does not alter production data when expenses.id is already bigint identity.

-- The local bootstrap creates expenses.id as UUID, while production has bigint
-- identity. Re-key only when safe; never silently invalidate attachment paths.
do $$
declare
  v_id_type text;
begin
  select data_type into v_id_type
  from information_schema.columns
  where table_schema = 'public' and table_name = 'expenses' and column_name = 'id';

  if v_id_type = 'uuid' then
    if exists (select 1 from storage.objects where bucket_id = 'expense-attachments')
       or exists (
         select 1 from public.expenses
         where attachment_path is not null
            or attachment_name is not null
            or attachment_status <> 'none'
            or attachment_uploaded_at is not null
            or attachment_uploaded_by is not null
            or attachment_last_error is not null
       ) then
      raise exception 'SCHEMA_ALIGNMENT_BLOCKED_EXPENSE_ATTACHMENTS: back up and reconcile local attachment paths before converting expenses.id';
    end if;

    if exists (
      select 1
      from information_schema.constraint_column_usage
      where table_schema = 'public' and table_name = 'expenses' and column_name = 'id'
        and constraint_name <> 'expenses_pkey'
    ) then
      raise exception 'SCHEMA_ALIGNMENT_BLOCKED_EXPENSE_ID_REFERENCE: expenses.id has dependent constraints';
    end if;

    -- Policies depend on expenses.id. Only drop them when the local UUID -> bigint
    -- conversion actually runs; production already has bigint identity and must keep
    -- its matching Storage policies untouched.
    execute 'drop policy if exists expense_attachments_select_v351 on storage.objects';
    execute 'drop policy if exists expense_attachments_insert_v351 on storage.objects';
    execute 'drop policy if exists expense_attachments_update_v351 on storage.objects';

    alter table public.expenses
      add column id__production bigint generated by default as identity;
    alter table public.expenses drop constraint if exists expenses_pkey;
    alter table public.expenses drop column id;
    alter table public.expenses rename column id__production to id;
    alter table public.expenses add constraint expenses_pkey primary key (id);
  elsif v_id_type <> 'bigint' then
    raise exception 'SCHEMA_ALIGNMENT_BLOCKED_UNEXPECTED_EXPENSE_ID_TYPE: %', v_id_type;
  end if;
end;
$$;

